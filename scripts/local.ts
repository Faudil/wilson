// Run Mon courrier on this computer without Docker (Windows, macOS, Linux). Needs only Bun (https://bun.sh).
//   bun install
//   bun local
// Back-office: http://localhost:5173 · data stored (encrypted) in ./.data · config in ./.env.local
import { randomBytes } from "node:crypto";
import { existsSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { Subprocess } from "bun";
import { readEnvFile } from "./env";

const root = join(import.meta.dir, "..");
const envFile = join(root, ".env.local");

if (!existsSync(envFile)) {
  const key = () => randomBytes(32).toString("base64");
  writeFileSync(
    envFile,
    [
      "# Generated by `bun local`. Keep MASTER_KEY safe: losing it = losing the data in .data/",
      `MASTER_KEY=${key()}`,
      `LOOKUP_KEY=${key()}`,
      "RUNTIME=local",
      `DATA_DIR=${join(root, ".data").replaceAll("\\", "/")}`,
      "WHATSAPP_MODE=sandbox",
      "LLM_MODE=fake",
      "# LLM_MODE=anthropic",
      "# ANTHROPIC_API_KEY=",
      "ASSOCIATION_NAME=Association Wilson",
      "ASSOCIATION_CONTACT=01 23 45 67 89 · 12 rue de l'Exemple, 75010 Paris · lun-ven 9h-17h",
      "SEED_ADMIN_EMAIL=admin@example.org",
      "SEED_ADMIN_PASSWORD=change-me-please",
      "",
    ].join("\n"),
  );
  console.log("Created .env.local with fresh encryption keys.");
}

const env: Record<string, string | undefined> = { ...process.env, ...readEnvFile(envFile), RUNTIME: "local", NODE_ENV: "development" };

if (!existsSync(join(root, "node_modules"))) {
  console.log("Installing dependencies…");
  const code = await Bun.spawn([process.execPath, "install"], { cwd: root, stdio: ["inherit", "inherit", "inherit"] }).exited;
  if (code !== 0) process.exit(code);
}

let stopping = false;
const children: Subprocess[] = [];

/** Prefix each line of a child's output with its name. */
async function pipe(name: string, stream: ReadableStream<Uint8Array>, write: (s: string) => void) {
  const decoder = new TextDecoder();
  let rest = "";
  for await (const chunk of stream) {
    const lines = (rest + decoder.decode(chunk, { stream: true })).split(/\r?\n/);
    rest = lines.pop() ?? "";
    for (const l of lines) if (l) write(`[${name}] ${l}`);
  }
  if (rest) write(`[${name}] ${rest}`);
}

// Bun runs the API and the web server directly (no package-manager or shell in between), so stopping a child
// really stops the server and frees its port, on Windows too.
function run(name: string, args: string[], cwd: string) {
  const child = Bun.spawn([process.execPath, ...args], { cwd: join(root, cwd), env, stdio: ["ignore", "pipe", "pipe"] });
  children.push(child);
  void pipe(name, child.stdout, console.log);
  void pipe(name, child.stderr, console.error);
  void child.exited.then((code) => {
    console.log(`[${name}] stopped (${code})`);
    stop(code ?? 0);
  });
}

function stop(code = 0) {
  if (stopping) return;
  stopping = true;
  // SIGTERM lets the API close the embedded database cleanly; force-kill whatever is left after 5 s.
  for (const c of children) if (c.exitCode === null) c.kill("SIGTERM");
  const timer = setTimeout(() => {
    for (const c of children) if (c.exitCode === null) c.kill("SIGKILL");
    process.exit(code);
  }, 5000);
  void Promise.all(children.map((c) => c.exited)).then(() => {
    clearTimeout(timer);
    process.exit(code);
  });
}

process.on("SIGINT", () => stop(0));
process.on("SIGTERM", () => stop(0));

run("api", ["src/main.ts"], "apps/api");
run("web", ["--hot", "serve.ts"], "apps/backoffice");

console.log(`
  Mon courrier (local, no Docker)
  ───────────────────────────────
  Back-office : http://localhost:5173   (${env.SEED_ADMIN_EMAIL} / ${env.SEED_ADMIN_PASSWORD})
  Sandbox     : http://localhost:5173/#/sandbox
  Data        : ${env.DATA_DIR}
  Stop        : Ctrl+C
`);
