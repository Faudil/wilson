#!/usr/bin/env node
// Run Mon courrier on this computer without Docker (Windows, macOS, Linux). Needs Node 22+ and pnpm.
//   pnpm install
//   pnpm local
// Back-office: http://localhost:5173 · data stored (encrypted) in ./.data · config in ./.env.local
import { spawn, spawnSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { existsSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { readEnvFile } from "./env.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const envFile = resolve(root, ".env.local");

if (!existsSync(envFile)) {
  const key = () => randomBytes(32).toString("base64");
  writeFileSync(
    envFile,
    [
      "# Generated by `pnpm local`. Keep MASTER_KEY safe: losing it = losing the data in .data/",
      `MASTER_KEY=${key()}`,
      `LOOKUP_KEY=${key()}`,
      "RUNTIME=local",
      `DATA_DIR=${resolve(root, ".data").replaceAll("\\", "/")}`,
      "WHATSAPP_MODE=sandbox",
      "LLM_MODE=fake",
      "# LLM_MODE=anthropic",
      "# ANTHROPIC_API_KEY=",
      "ASSOCIATION_NAME=Association Wilson",
      "ASSOCIATION_CONTACT=01 23 45 67 89 · 12 rue de l'Exemple, 75010 Paris · lun-ven 9h-17h",
      "SEED_ADMIN_EMAIL=admin@example.org",
      "SEED_ADMIN_PASSWORD=change-me-please",
      "",
    ].join("\n"),
  );
  console.log("Created .env.local with fresh encryption keys.");
}

const env = { ...process.env, ...readEnvFile(envFile) };
env.RUNTIME = "local";
env.NODE_ENV = "development";

if (!existsSync(resolve(root, "node_modules"))) {
  console.log("Installing dependencies…");
  const r = spawnSync("pnpm", ["install"], { cwd: root, stdio: "inherit", shell: true });
  if (r.status !== 0) process.exit(r.status ?? 1);
}

const run = (name, args) => {
  // detached on POSIX = own process group, so stop() can kill pnpm *and* the node server it started.
  const child = spawn("pnpm", args, { cwd: root, env, stdio: ["ignore", "pipe", "pipe"], shell: true, detached: process.platform !== "win32" });
  const prefix = (chunk) => chunk.toString().split(/\r?\n/).filter(Boolean).map((l) => `[${name}] ${l}`).join("\n");
  child.stdout.on("data", (c) => console.log(prefix(c)));
  child.stderr.on("data", (c) => console.error(prefix(c)));
  child.on("exit", (code) => {
    console.log(`[${name}] stopped (${code})`);
    stop();
    setTimeout(() => process.exit(code ?? 0), process.platform === "win32" ? 6000 : 500);
  });
  return child;
};

const children = [
  run("api", ["--filter", "@wilson/api", "start"]),
  run("web", ["--filter", "@wilson/backoffice", "dev", "--", "--port", "5173", "--strictPort"]),
];
// Kill the whole process tree (shell → pnpm → node), otherwise the API keeps port 3000 busy after Ctrl+C.
const killTree = (c) => {
  if (!c.pid) return;
  // Windows: Ctrl+C already reaches every process of the console; give the API time to close the database
  // cleanly, then force-kill whatever is left.
  if (process.platform === "win32") setTimeout(() => spawnSync("taskkill", ["/pid", String(c.pid), "/T", "/F"], { stdio: "ignore" }), 5000);
  else {
    try {
      process.kill(-c.pid, "SIGTERM");
    } catch {
      c.kill("SIGTERM");
    }
  }
};
const stop = () => children.forEach(killTree);
process.on("SIGINT", stop);
process.on("SIGTERM", stop);

console.log(`
  Mon courrier (local, no Docker)
  ───────────────────────────────
  Back-office : http://localhost:5173   (${env.SEED_ADMIN_EMAIL} / ${env.SEED_ADMIN_PASSWORD})
  Sandbox     : http://localhost:5173/#/sandbox
  Data        : ${env.DATA_DIR}
  Stop        : Ctrl+C
`);
